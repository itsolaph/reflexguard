"""Render ml/report.md from the training results."""
import math


def pct(x):
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}%"


def pct3(x):
    """Percentage with three decimals, for rates that are well below 1%."""
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.3f}%"


def wilson(k, n, z=1.96):
    """95% Wilson interval for a proportion, as a string."""
    if n == 0:
        return "n/a"
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return f"{100 * (c - h):.0f}-{100 * (c + h):.0f}%"


def swap_rows(res, names):
    rows = ["| split | swaps | positives | AUC | precision | recall | FPR | TP | FP | FN | TN |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name in names:
        s = res["splits"][name]
        m = s["swap"]
        rows.append(f"| {name} | {s['n_swaps']} | {s['n_pos']} | {m['auc']:.4f} | {pct(m['precision'])} | "
                    f"{pct(m['recall'])} | {pct3(m['fpr'])} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} |")
    return rows


def episode_rows(res, names):
    rows = ["| split | benign scenarios | false-halt rate | A caught | A early | B caught | B early | C caught | C early |",
            "|---|---|---|---|---|---|---|---|---|"]
    for name in names:
        e = res["splits"][name]["episodes"]

        def cell(fam, key):
            return pct(e[fam][key]) if fam in e else "-"
        rows.append(f"| {name} | {e['benign_scenarios']} | {pct(e['benign_false_halt_rate'])} | "
                    f"{cell('A', 'caught')} | {cell('A', 'early')} | {cell('B', 'caught')} | {cell('B', 'early')} | "
                    f"{cell('C', 'caught')} | {cell('C', 'early')} |")
    return rows


def write(path, gen, final, a_gap, demo, parts, cfg):
    L = []
    add = L.append
    add("# ReflexGuard model report")
    add("")
    add("Generated by `ml/train.py`. All data is synthetic (`ml/sim.py`); nothing here says how the model "
        "behaves on real pools. Numbers are for the integer model that runs on-chain.")
    add("")
    add("## Setup")
    add("")
    add(f"- Seed {cfg['seed']}. {cfg['benign_each']} scenarios for each of 4 benign regimes (retail, whale, arb, burst) "
        f"and {cfg['attack_each']} for each attack family (A pump-and-dump, B sandwich, C slow drip).")
    add("- Split 60/20/20 per scenario kind into train/val/test. Scenarios are independent pools, so there is no "
        "leakage across splits within a scenario.")
    add("- Positive label: only the swaps that unwind the attacker's position (A, B, C). The opening legs "
        "(pump, front-run, victim swap, drip swaps) are labelled 0: on-chain they look like a whale, a victim "
        "or an honest burst. A guard that fires on them anyway is counted as `early` for attack scenarios and as "
        "a false positive in the per-swap tables.")
    add("- Per-swap metrics use the shipped threshold. An *episode* is one scenario: **caught** = some "
        "positive-labelled swap reached the threshold; **early** = some swap *before* the first unwinding leg "
        "did (the pool would have been paused before the attacker started to unwind); **false-halt rate** = share "
        "of benign scenarios in which at least one swap reached the threshold (each of those would pause a "
        "legitimate pool).")
    add(f"- Threshold chosen on validation scenarios: the highest episode catch rate subject to a benign "
        f"false-halt rate <= {pct(cfg['target'])}. Best of 3 seeded restarts by the same criterion.")
    add("")
    add("## 1. Generalisation: family C held out")
    add("")
    add(f"Trained on benign + A + B only. Threshold {gen['threshold']}. Family C scenarios (all splits, "
        f"{gen['heldout']['n']} scenarios) were never used for training, threshold choice or restart selection.")
    add("")
    add("Per-swap metrics on the seen families:")
    add("")
    L.extend(swap_rows(gen, ["train", "val", "test"]))
    add("")
    add("Episode metrics (family C is excluded from these rows; it is reported separately below):")
    add("")
    L.extend(episode_rows(gen, ["train", "val", "test"]))
    add("")
    h = gen["heldout"]
    c = h["episodes"]["C"]
    n = c["n"]
    add("**Held-out family C, all scenarios:**")
    add("")
    add("| metric | value | 95% CI |")
    add("|---|---|---|")
    add(f"| episodes caught (any positive swap flagged) | {pct(c['caught'])} | {wilson(round(c['caught'] * n), n)} |")
    add(f"| unwinding legs flagged (mean per episode) | {pct(c['reversal_leg_recall'])} | |")
    add(f"| flagged before the first unwinding leg (early) | {pct(c['early'])} | {wilson(round(c['early'] * n), n)} |")
    m = h["swap"]
    add(f"| per-swap recall on C-labelled swaps | {pct(m['recall'])} | |")
    add(f"| per-swap AUC on C scenarios | {m['auc']:.4f} | |")
    add("")
    add("## 2. Shipped model: trained on everything")
    add("")
    add(f"Benign + A + B + C. Threshold **{final['threshold']}** (score range 0..10000). 65 int16 weights.")
    add("")
    L.extend(swap_rows(final, ["train", "val", "test"]))
    add("")
    L.extend(episode_rows(final, ["train", "val", "test"]))
    add("")
    add("Per-swap metrics on the test split by family (FPR on the attack rows counts unlabelled legs of the "
        "attack, e.g. the pump):")
    add("")
    add("| family | swaps | positives | AUC | precision | recall | FPR |")
    add("|---|---|---|---|---|---|---|")
    for fam, m in final["splits"]["test"]["by_family"].items():
        add(f"| {fam} | {m['tp'] + m['fp'] + m['fn'] + m['tn']} | {m['tp'] + m['fn']} | {m['auc']:.4f} | "
            f"{pct(m['precision'])} | {pct(m['recall'])} | {pct3(m['fpr'])} |")
    add("")
    t = final["splits"]["test"]["swap"]
    add("Confusion table, test split, per swap:")
    add("")
    add("| | flagged | not flagged |")
    add("|---|---|---|")
    add(f"| positive | {t['tp']} | {t['fn']} |")
    add(f"| negative | {t['fp']} | {t['tn']} |")
    add("")
    add("## 3. Float vs integer model")
    add("")
    add("| run | split | decision agreement at threshold | mean abs score diff | max abs score diff | float AUC | int AUC |")
    add("|---|---|---|---|---|---|---|")
    for res, name in ((gen, "generalisation"), (final, "final")):
        for split in ("train", "val", "test"):
            s = res["splits"][split]
            add(f"| {name} | {split} | {pct(s['float_int_agreement'])} | {s['float_int_mean_abs_diff']:.1f} | "
                f"{s['float_int_max_abs_diff']:.1f} | {s['float_auc']:.4f} | {s['swap']['auc']:.4f} |")
    add("")
    add("Score differences are in score units (0..10000). The integer model uses Q8 weights, truncating shifts "
        "and a 33-point sigmoid table.")
    add("")
    add("## 4. Where it fails")
    add("")
    e = final["splits"]["test"]["episodes"]
    add("False halts on benign test scenarios by regime (halted / scenarios):")
    add("")
    add("| regime | false halts |")
    add("|---|---|")
    for kind, (k, total) in e["benign_by_kind"].items():
        add(f"| {kind} | {k} / {total} |")
    add("")
    add("Family A (test split) caught by time between the pump and the first unwinding leg:")
    add("")
    add("| gap | scenarios | any unwinding leg flagged |")
    add("|---|---|---|")
    for label, total, hit in a_gap:
        add(f"| {label} | {total} | {hit} |")
    add("")
    add("Structural limits, independent of the numbers above:")
    add("")
    add("- The opening leg of A and B (the pump, the front-run) cannot be told from a whale swap or a victim "
        "swap. The guard can only react to the unwinding. The `early` columns show how often the guard fires "
        "before the unwind starts; for A and B that is by construction close to 0%, so the first unwinding leg "
        "of such an attack usually executes. Multi-leg unwinds are interrupted; a single-leg unwind is not.")
    add("- The callback is not instantaneous: the halt lands some seconds after the triggering swap. Swaps in "
        "between are not stopped.")
    add("- A whale swap that is arbitraged back within seconds looks like a pump-and-dump. The simulator "
        "includes only slow arbitrage-back (25 s or more) after whale swaps, so these numbers say nothing "
        "about fast arbitrage on a real chain.")
    add("")
    add("## 5. Demo plan under timing jitter")
    add("")
    add("`ml/demo_plan.json` replayed 300 times per column with every gap drawn at random (the live demo cannot "
        "hit exact gaps: `cast send` waits for the receipt, and several swaps can land in the same second):")
    add("")
    narrow, wide = demo["narrow"], demo["wide"]
    add("| outcome (trials of 300) | gaps 2, 3 or 4 s | gaps 0..12 s |")
    add("|---|---|---|")
    for label, key in (("whale / warm-up swaps flagged (false halt)", "whale_halted"),
                       ("pump-and-dump flagged on some leg", "attack_halted"),
                       ("flagged already on the first dump leg", "dump1_halted"),
                       ("drip flagged on some swap", "drip_halted"),
                       ("drip flagged before the reversal swap", "drip_before_reverse")):
        add(f"| {label} | {narrow[key]} | {wide[key]} |")
    add("")
    with open(path, "w") as fh:
        fh.write("\n".join(L) + "\n")
